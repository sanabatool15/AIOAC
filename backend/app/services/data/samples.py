"""Bundled synthetic datasets so the demo never depends on live dataset search (specs/data.md)."""
import io

import numpy as np
import pandas as pd


def churn_csv(rows: int = 4800, seed: int = 0) -> bytes:
    rng = np.random.default_rng(seed)
    months = rng.integers(1, 60, rows)
    days_since = rng.integers(0, 120, rows)
    orders = rng.poisson(6, rows)
    plan = rng.choice(["basic", "plus", "pro"], rows, p=[0.5, 0.3, 0.2])
    logit = -3.0 + 0.07 * days_since - 0.06 * months - 0.25 * orders + (plan == "basic") * 0.8
    left = (rng.random(rows) < 1 / (1 + np.exp(-logit))).astype(int)
    df = pd.DataFrame({"months_active": months, "days_since_last_purchase": days_since,
                       "orders_this_year": orders, "plan": plan, "left": np.where(left == 1, "Yes", "No")})
    df.loc[rng.random(rows) < 0.03, "orders_this_year"] = np.nan
    buf = io.StringIO()
    df.to_csv(buf, index=False)
    return buf.getvalue().encode()


